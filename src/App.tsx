import { useEffect, useState } from 'react'
import { Routes, Route, Navigate } from 'react-router-dom'
import { supabase } from './lib/supabase'
import { useAuth } from './lib/AuthContext'
import { looksAutoGenerated, USERNAME_FLAG_KEY } from './lib/username'
import Layout from './components/Layout'
import RequireAuth from './components/RequireAuth'
import Feed from './pages/Feed'
import PoemPage from './pages/PoemPage'
import WritePoem from './pages/WritePoem'
import Profile from './pages/Profile'
import TagPage from './pages/TagPage'
import MyPoems from './pages/MyPoems'
import LikedPoems from './pages/LikedPoems'
import Login from './pages/Login'
import UsernameSetup from './pages/UsernameSetup'

export default function App() {
  const { session, loading } = useAuth()
  const [checking, setChecking] = useState(false)
  const [needsSetup, setNeedsSetup] = useState(false)

  // After login, if the username was auto-generated, send the user to pick one.
  useEffect(() => {
    if (!session || loading) return

    // The user already chose a username in this browser — don't nag them again.
    if (localStorage.getItem(USERNAME_FLAG_KEY) === '1') {
      setNeedsSetup(false)
      return
    }

    let cancelled = false
    setChecking(true)
    supabase
      .from('profiles')
      .select('username')
      .eq('id', session.user.id)
      .maybeSingle()
      .then(({ data }) => {
        if (cancelled) return
        setChecking(false)
        if (!data) return
        const auto = looksAutoGenerated(
          data.username,
          session.user.user_metadata || {}
        )
        setNeedsSetup(auto)
      })

    return () => {
      cancelled = true
    }
  }, [session, loading])

  if (loading || (session && checking)) {
    return <div className="page-loading">Loading…</div>
  }

  return (
    <Routes>
      <Route path="/" element={<Layout />}>
        <Route
          index
          element={needsSetup ? <Navigate to="/setup" replace /> : <Feed />}
        />
        <Route path="poem/:id" element={<PoemPage />} />
        <Route path="tag/:name" element={<TagPage />} />
        <Route path="u/:username" element={<Profile />} />
        <Route
          path="write"
          element={
            <RequireAuth>
              <WritePoem />
            </RequireAuth>
          }
        />
        <Route
          path="edit/:id"
          element={
            <RequireAuth>
              <WritePoem />
            </RequireAuth>
          }
        />
        <Route
          path="my-poems"
          element={
            <RequireAuth>
              <MyPoems />
            </RequireAuth>
          }
        />
        <Route
          path="liked"
          element={
            <RequireAuth>
              <LikedPoems />
            </RequireAuth>
          }
        />
        <Route
          path="login"
          element={session ? <Navigate to="/" replace /> : <Login />}
        />
        <Route
          path="setup"
          element={
            session ? <UsernameSetup /> : <Navigate to="/login" replace />
          }
        />
        <Route path="*" element={<Navigate to="/" replace />} />
      </Route>
    </Routes>
  )
}
